/**
 * PaymentProvider interface (duck-typed, no base class needed in JS):
 *   initiate({ payment, order }) -> Promise<{ status, providerReference, payload }>
 *   checkStatus({ payment })     -> Promise<{ status, payload }>
 *
 * status is one of: PENDING | PROCESSING | PAID | FAILED
 */

export class ManualPaymentProvider {
  // Cash, or a Kaspi transfer arranged directly between rider and driver:
  // there is nothing to call electronically here. Settlement is confirmed
  // by an operator via POST /orders/:id/mark-paid (orders.routes.js), which
  // this class does not touch. It exists so that path still goes through
  // the same {status, providerReference, payload} shape as the real
  // provider below, instead of being a special case in the routes.
  async initiate() {
    return { status: "PENDING", providerReference: null, payload: {} };
  }

  async checkStatus({ payment }) {
    return { status: payment.status, payload: payment.provider_payload || {} };
  }
}

// How long the mock takes to "settle" a payment, and how often it pretends
// the bank/gateway declined it — purely so the app's processing/failed/retry
// states are actually exercisable before a real gateway exists.
const MOCK_RESOLVE_DELAY_MS = 4000;
const MOCK_FAILURE_RATE = 0.1;

// Used whenever real Kaspi Pay credentials aren't configured (see
// isKaspiPayConfigured below) — same simulated PROCESSING-then-resolves
// behavior as before this file was updated, so nothing about local dev or
// any other session's tests changes until KASPI_MERCHANT_ID/KASPI_API_KEY/
// KASPI_API_BASE_URL are actually set.
export class MockKaspiPayProvider {
  async initiate({ payment }) {
    const providerReference = `MOCK-KZP-${crypto.randomUUID()}`;
    scheduleMockResolution(payment.id);
    return {
      status: "PROCESSING",
      providerReference,
      payload: {
        mock: true,
        redirectUrl: null,
        note: "Kaspi Pay API is not connected yet. This is a simulated PROCESSING state for UI/testing purposes."
      }
    };
  }

  async checkStatus({ payment }) {
    return { status: payment.status, payload: payment.provider_payload || {} };
  }
}

function scheduleMockResolution(paymentId) {
  setTimeout(async () => {
    try {
      const outcome = Math.random() < MOCK_FAILURE_RATE
        ? { status: "FAILED", reason: "Mock decline: insufficient funds (simulated)" }
        : { status: "PAID", reason: null };
      await query(
        `UPDATE payments
         SET status=$1, failure_reason=$2,
             provider_payload = provider_payload || $3::jsonb, updated_at=NOW()
         WHERE id=$4 AND status='PROCESSING'`,
        [
          outcome.status,
          outcome.reason,
          JSON.stringify({ mockResolvedAt: new Date().toISOString() }),
          paymentId
        ]
      );
    } catch (error) {
      console.error("[payments] mock Kaspi Pay auto-resolve failed", error);
    }
  }, MOCK_RESOLVE_DELAY_MS);
}

// --- Real Kaspi Pay integration ------------------------------------------
//
// What's authoritative here, and what isn't — read this before touching
// endpoint paths:
//
// Kaspi's one publicly available technical spec (Технический регламент,
// https://kaspipay.kz/documents/) documents the "MPP" (Mobile Payment
// Provider) program: an integration for OTHER apps/banks that want their
// own app to scan Kaspi QR codes generated by a merchant, secured over a
// dedicated IPSec VPN tunnel between Kaspi and the partner's servers —
// not a plain internet-facing REST API with a bearer token. That is a
// different product from what SmartTaxi needs (a backend that creates a
// payment request for a specific order and gets a webhook when it's
// settled). The HTTP *conventions* below (JSON bodies, ISO 8601
// timestamps, amounts as 2-decimal strings, X-Request-ID / X-Caller-Name
// headers, a {result: {resultCode, resultMessage}} response envelope, and
// the general create -> notify -> refund shape) are taken directly from
// that document and can be trusted. The exact base URL and endpoint paths
// for a *merchant-initiated* payment are not published anywhere public —
// Kaspi's partner-onboarding team hands those over, along with real
// credentials, once the business partnership application
// (kaspi.kz/webpay/partnership) is approved. The paths below are best-effort
// placeholders following the documented conventions, not confirmed
// endpoints — see docs/status/KASPI_PAY_READINESS_2026-07-15.md for what to
// do with the real docs once they arrive.
const KASPI_PATHS = {
  createPayment: "/payments",
  paymentStatus: (paymentId) => `/payments/${encodeURIComponent(paymentId)}`,
  refund: (paymentId) => `/payments/${encodeURIComponent(paymentId)}/refund`
};

function kaspiHeaders(apiKey) {
  return {
    "Content-Type": "application/json",
    Authorization: `Bearer ${apiKey}`,
    "X-Request-ID": crypto.randomUUID(),
    // Kaspi's docs cap this at 12 characters for the MPP flow; kept short
    // here on the same assumption until confirmed otherwise.
    "X-Caller-Name": "SmartTaxi"
  };
}

// Kaspi's documented amount format is a plain decimal string with 2 places
// (e.g. "100.00"), not integer minor units — orders.price/payments.amount
// are whole tenge in this codebase, so this is a straight toFixed(2).
function formatAmount(amountKzt) {
  return Number(amountKzt).toFixed(2);
}

async function kaspiRequest(path, { method = "POST", body } = {}) {
  const url = `${env.KASPI_API_BASE_URL.replace(/\/$/, "")}${path}`;
  const response = await fetch(url, {
    method,
    headers: kaspiHeaders(env.KASPI_API_KEY),
    body: body ? JSON.stringify(body) : undefined
  });
  let data = {};
  try {
    data = await response.json();
  } catch {
    // Non-JSON error body from the gateway — fall through with an empty
    // object so callers still get a sensible resultCode-shaped failure
    // below instead of throwing on `data.result`.
  }
  return { response, data };
}

export class KaspiPayProvider {
  async initiate({ payment, order }) {
    const { response, data } = await kaspiRequest(KASPI_PATHS.createPayment, {
      body: {
        merchantId: env.KASPI_MERCHANT_ID,
        amount: formatAmount(payment.amount),
        currency: payment.currency || "KZT",
        orderId: order.short_id || order.id,
        // Where Kaspi should send the customer back / where the QR content
        // resolves to — exact field name unconfirmed, see module comment.
        description: `SmartTaxi: поездка ${order.short_id || order.id}`
      }
    });

    const resultCode = data?.result?.resultCode;
    if (!response.ok || resultCode !== "SUCCESS") {
      return {
        status: "FAILED",
        providerReference: null,
        payload: {
          raw: data,
          httpStatus: response.status,
          resultMessage: data?.result?.resultMessage || "Kaspi Pay request failed"
        }
      };
    }

    return {
      status: "PROCESSING",
      providerReference: data.paymentId || data.payment?.paymentId || null,
      payload: {
        redirectUrl: data.redirectUrl || data.payment?.redirectUrl || null,
        qrCode: data.qrCode || data.payment?.qrCode || null,
        canConfirmUntil: data.canConfirmUntil || data.payment?.canConfirmUntil || null,
        raw: data
      }
    };
  }

  async checkStatus({ payment }) {
    if (!payment.provider_reference) {
      return { status: payment.status, payload: payment.provider_payload || {} };
    }
    const { response, data } = await kaspiRequest(KASPI_PATHS.paymentStatus(payment.provider_reference), {
      method: "GET"
    });
    if (!response.ok) {
      // A transient failure to check status isn't the same as the payment
      // having failed — keep polling rather than flip it to FAILED on a
      // network blip.
      return { status: payment.status, payload: payment.provider_payload || {} };
    }
    const status = mapKaspiStatus(data?.status || data?.result?.resultCode);
    return { status, payload: { raw: data } };
  }
}

export function mapKaspiStatus(kaspiStatus) {
  switch (kaspiStatus) {
    case "SUCCESS":
    case "PAID":
    case "COMPLETED":
      return "PAID";
    case "CANCELLED_BY_CLIENT":
    case "FAILED":
    case "PROCESS_FAIL":
    case "RISK_REJECT":
      return "FAILED";
    default:
      return "PROCESSING";
  }
}

// Verifies an incoming webhook's signature before its payload is trusted.
// Kaspi's own signature scheme for merchant webhooks isn't in the one
// public spec available (see module comment) — this implements the
// industry-standard pattern (HMAC-SHA256 over the raw request body, hex
// digest, compared in constant time) used by essentially every payment
// gateway's webhook, via a shared secret issued at onboarding
// (KASPI_WEBHOOK_SECRET). If Kaspi's real docs specify a different header
// name or algorithm, only this function needs to change — every call site
// just calls verifyKaspiWebhookSignature(rawBody, signatureHeader).
export function verifyKaspiWebhookSignature(rawBody, signatureHeader) {
  if (!env.KASPI_WEBHOOK_SECRET) return false;
  if (!signatureHeader) return false;
  const expected = crypto
    .createHmac("sha256", env.KASPI_WEBHOOK_SECRET)
    .update(rawBody)
    .digest("hex");
  const expectedBuffer = Buffer.from(expected, "utf8");
  const providedBuffer = Buffer.from(String(signatureHeader), "utf8");
  if (expectedBuffer.length !== providedBuffer.length) return false;
  return crypto.timingSafeEqual(expectedBuffer, providedBuffer);
}

// Used both for the "cancel an already-paid order" refund-to-cashback path
// (finance.service.js) and for a future admin-initiated refund action.
// Throws rather than returning a soft failure — callers refund real money
// and should not silently treat a failed refund call as a success.
export async function refundKaspiPayment({ payment, amountKzt }) {
  if (!isKaspiPayConfigured()) {
    throw new AppError("Kaspi Pay is not configured", 503, "KASPI_PAY_NOT_CONFIGURED");
  }
  if (!payment.provider_reference) {
    throw new AppError("Payment has no Kaspi Pay reference to refund", 400, "PAYMENT_NOT_REFUNDABLE");
  }
  const { response, data } = await kaspiRequest(KASPI_PATHS.refund(payment.provider_reference), {
    body: { amount: formatAmount(amountKzt ?? payment.amount) }
  });
  const resultCode = data?.result?.resultCode;
  if (!response.ok || resultCode !== "SUCCESS") {
    throw new AppError(
      data?.result?.resultMessage || "Kaspi Pay refund failed",
      502,
      "KASPI_REFUND_FAILED",
      { raw: data }
    );
  }
  return { refundId: data.refundId || data.refund?.refundId || null, raw: data };
}

function isKaspiPayConfigured() {
  return Boolean(env.KASPI_MERCHANT_ID && env.KASPI_API_KEY && env.KASPI_API_BASE_URL);
}

const PROVIDER_BY_METHOD = {
  // CASH and KASPI are today both settled directly between rider and driver
  // ("Перевод по договорённости с водителем" in the app's copy) and
  // confirmed by an operator — no ИП/merchant account exists yet to collect
  // Kaspi payments through a gateway, so KASPI stays manual for now.
  CASH: "MANUAL",
  KASPI: "MANUAL",
  // CARD is the new, forward-looking option: it has no manual-settlement
  // story (nobody hands a driver a card payment), so it's wired straight to
  // the gateway. Once the real Kaspi Pay merchant credentials exist, this
  // is also the natural place to move KASPI to "KASPI_PAY" — Kaspi Pay
  // checkout supports both wallet and card payment in one flow.
  CARD: "KASPI_PAY"
};

const manualProvider = new ManualPaymentProvider();

export function providerNameForMethod(method) {
  return PROVIDER_BY_METHOD[method] || "MANUAL";
}

export function getPaymentProvider(providerName) {
  if (providerName === "KASPI_PAY") {
    // Decided fresh on every call (not a module-load-time singleton) so
    // setting the env vars takes effect without a restart being the only
    // way to notice, and so tests can toggle env.* between cases.
    return isKaspiPayConfigured() ? new KaspiPayProvider() : new MockKaspiPayProvider();
  }
  return manualProvider;
}
